CREATE TABLE talepler (
    id        bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    baslik    text        NOT NULL CHECK (length(trim(baslik)) > 0),
    durum     text        NOT NULL DEFAULT 'acik'
                          CHECK (durum IN ('acik', 'beklemede', 'kapali')),
    oncelik   text        NOT NULL CHECK (oncelik IN ('yuksek', 'orta', 'dusuk')),
    musteri   text        NOT NULL CHECK (musteri LIKE '%_@_%'),
    etiketler text[]      NOT NULL DEFAULT '{}',
    acildi    timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX talepler_durum_idx ON talepler (durum);
